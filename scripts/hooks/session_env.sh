#!/usr/bin/env bash
# SessionStart | CwdChanged. Gives the agent harness the same environment direnv gives an
# interactive shell, by exporting scripts/env.sh into CLAUDE_ENV_FILE -- with ONE deliberate
# difference: LDE_HOME is redirected to .dev-state/ so a session never mutates the real corpora.
set -uo pipefail
. "$(dirname "${BASH_SOURCE[0]}")/_common.sh"
hook_read_input
root="$(hook_root)"
[ -n "${CLAUDE_ENV_FILE:-}" ] || exit 0
[ -f "${root}/scripts/env.sh" ] || exit 0
mkdir -p "${root}/.dev-state/bin" 2>/dev/null || true

python3 - "$root" > "$CLAUDE_ENV_FILE" <<'PY'
import json, subprocess, sys
root = sys.argv[1]
script = (f'set -a; export LDE_ROOT={root!r}; export LDE_HOME={root + "/.dev-state"!r}; '
          f'. {root}/scripts/env.sh; python3 -c "import os,json;print(json.dumps(dict(os.environ)))"')
try:
    out = subprocess.run(["bash", "-c", script], capture_output=True, text=True, timeout=15)
    after = json.loads(out.stdout.strip().splitlines()[-1])
except Exception:
    raise SystemExit
print("# generated by scripts/hooks/session_env.sh from scripts/env.sh -- do not edit")
for k in ("LDE_ROOT", "LDE_HOME", "RUST_BACKTRACE", "CARGO_TERM_COLOR", "RUSTC_WRAPPER",
          "CARGO_TARGET_X86_64_UNKNOWN_LINUX_GNU_RUSTFLAGS", "UV_PROJECT_ENVIRONMENT",
          "UV_NO_SYNC", "PYTHONDONTWRITEBYTECODE", "PATH"):
    if k in after:
        print(f"export {k}={after[k]!r}")
print("unset RUSTUP_TOOLCHAIN")
PY
exit 0
